"""Legacy skill-stats migration (ADR-0005): one verb that moves a Target repo
from the pre-rename layout to coding-stats.

Migrated surfaces per repo:

* the committed artifact (``.skill-stats/skill-stats.sql`` -> a fresh
  ``.coding-stats/`` store, regenerated by the normal update flow),
* the machine-local working DB (``~/.skill-stats/skill-stats.db`` reused
  when it corresponds to the legacy artifact AND is not behind it — verdicts
  and classify session survive; otherwise the DB is rebuilt from the legacy
  artifact bytes, whose verdict rows travel inside the artifact; the two are
  never silently merged and the newer side always wins),
* the Repository key when the GitHub rename changed it: the tool's identity
  rules (identity.register_repository) refuse key changes on DBs holding
  data — correctly, they cannot tell a rename from pointing a DB at a
  different repo. Migration is the explicit, user-invoked authority for
  that one case: it first verifies the legacy artifact digest, establishing
  that the DB and the artifact carry the same repository's analysis
  (consistency under the artifact threat model — the digest is an unkeyed
  checksum, not a forgery proof), and only then relabels the key to the
  resolved (post-rename) identity.
* the CI scaffold: the legacy ``skill-stats.yml`` is deleted (it would keep
  running the old tool forever) and ``ci init`` optionally writes the new
  workflow.

Existing destination DBs holding another repository's data are refused, not
overwritten; a destination holding a previous attempt at THIS repository
(same expected key) is replaced. Swaps are atomic and the legacy
``.skill-stats/`` directory is removed only after the regenerated new store
verifies on disk — a failed update never destroys the old artifact. The
second run of this verb is a no-op cleanup (idempotent).
"""

import argparse
import json
import shutil
import sqlite3
import subprocess
from dataclasses import dataclass
from pathlib import Path

from . import artifact, db, identity, recovery

OLD_STORE_DIR = ".skill-stats"
OLD_ARTIFACT_REL = ".skill-stats/skill-stats.sql"
OLD_WORKFLOW_REL = ".github/workflows/skill-stats.yml"
NEW_ARTIFACT_REL = ".coding-stats/coding-stats.sql"

DEFAULT_LEGACY_DB = Path("~/.skill-stats/skill-stats.db")
DEFAULT_MIRRORED_DB = Path("~/.coding-stats/coding-stats.db")

_SIDECARS = ("-wal", "-shm", "-journal")


class MigrationError(RuntimeError):
    """Migration cannot proceed safely; nothing was changed."""


@dataclass(frozen=True)
class Plan:
    """What migrate will do and why. Printed verbatim by --dry-run."""

    seed: str  # 'already' | 'reuse-db' | 'rebuild-artifact' | 'fresh'
    db_path: Path
    legacy_db: Path | None
    relabel: tuple[str, str, str, str] | None  # stored key, base, slug, new key
    notices: tuple[str, ...]
    cleanup: tuple[str, ...]
    branch: str


def detect(
    repo: Path,
    db_arg: str | None,
    legacy_arg: str | None,
    fresh: bool,
    branch: str,
) -> Plan:
    """Inspect the repo's legacy state and decide the seed, the destination
    DB, the rename relabel, and the cleanup list. Explicit user input
    (--legacy-db paths, destinations holding foreign data) that contradicts
    reality is an error; implicit defaults (a legacy DB found at the default
    path) never are — they downgrade to a safer seed with a notice."""
    base, slug, resolved = _resolved_key(repo, branch)
    cleanup: list[str] = []
    if (repo / OLD_WORKFLOW_REL).exists():
        cleanup.append(OLD_WORKFLOW_REL)
    if (repo / OLD_STORE_DIR).exists():
        cleanup.append(OLD_STORE_DIR + "/")
    notices: list[str] = []

    # --fresh overrides everything: even a valid new-format artifact is
    # recomputed (the still-present legacy files are cleaned up afterwards)
    if fresh:
        db_path = Path(db_arg) if db_arg else _default_dest()
        _guard_dest(db_path, None, fresh=True)
        return Plan("fresh", db_path, None, None, tuple(notices), tuple(cleanup), branch)

    db_path = _dest_choice(db_arg, legacy_arg)
    legacy_db = _legacy_db_path(legacy_arg)

    new_art = repo / NEW_ARTIFACT_REL
    if new_art.exists() and artifact.verify(new_art) is None:
        header = artifact.parse_header(new_art.read_bytes(), require_tag=False)
        if header is not None and header.repository_key != resolved:
            raise MigrationError(
                f"{new_art} verifies but is keyed {header.repository_key!r}, not this"
                " repository's identity — not crediting migration; resolve manually"
                " or run with --fresh"
            )
        return Plan("already", db_path, None, None, tuple(notices), tuple(cleanup), branch)

    old_art = repo / OLD_ARTIFACT_REL
    err = artifact.verify(old_art) if old_art.exists() else "missing"
    if err is not None:
        if err != "missing":
            notices.append(f"legacy artifact fails verification ({err}); migrating fresh")
        return Plan("fresh", db_path, None, None, tuple(notices), tuple(cleanup), branch)
    header = artifact.parse_header(old_art.read_bytes(), require_tag=False)
    if header is None:
        notices.append("legacy artifact has no parsable header; migrating fresh")
        return Plan("fresh", db_path, None, None, tuple(notices), tuple(cleanup), branch)

    stored = header.repository_key
    explicit = legacy_arg is not None
    if legacy_db is not None:
        db_key = _stored_db_key(legacy_db)
        if db_key is None:
            # no repositories row: an empty DB or a pre-step-1 legacy schema.
            # The committed artifact is the authority either way — rebuild
            # from it instead of aborting (a raw file copy of a live WAL DB
            # can legitimately trail its rows).
            notices.append(
                f"ignoring {legacy_db}: no repositories row (empty or pre-step-1"
                " legacy DB); rebuilding from the artifact"
            )
            legacy_db = None
        elif db_key != stored:
            if explicit:
                raise MigrationError(
                    f"legacy DB {legacy_db} is keyed {db_key!r} but the legacy artifact is"
                    f" keyed {stored!r} — they do not correspond; migrate without"
                    " --legacy-db or with --fresh"
                )
            notices.append(
                f"ignoring {legacy_db}: keyed {db_key!r}, not this repository's legacy artifact"
            )
            legacy_db = None
    else:
        notices.append(
            "no legacy machine DB found; seeding the new DB from the legacy artifact"
            " (verdicts travel inside it)"
        )

    relabel: tuple[str, str, str, str] | None = None
    stored_shim = stored.startswith("local:")
    resolved_shim = base.startswith("local:")
    if stored == resolved:
        pass
    elif not stored_shim and not resolved_shim:
        relabel = (stored, base, slug, resolved)  # the GitHub rename, by explicit authority
    elif stored_shim and resolved_shim:
        raise MigrationError(
            f"legacy identity {stored!r} cannot relabel to {resolved!r}"
            " (shim-to-shim move); migrate with --fresh"
        )
    elif stored_shim:
        # shim -> canonical is the documented upgrade flow: register_repository
        # relabels it (with a warning) during the post-migration update
        notices.append(
            f"shim identity {stored!r} upgrades to the canonical {resolved!r}"
            " during the migration update"
        )
    else:
        notices.append(
            f"origin URL unavailable on this machine (resolved {resolved!r}); the stored"
            f" key {stored!r} is kept — register_repository warns and continues"
        )

    if legacy_db is not None:
        relation = _horizon_relation(repo, legacy_db, header.covered_through)
        if db_key is None:
            # no repositories row: an empty DB or a pre-step-1 legacy schema.
            # The key cannot be verified, so the DB is never REUSED — but the
            # artifact stays authoritative and the horizon relation still
            # tells the user where their DB stood.
            notices.append(
                f"ignoring {legacy_db} for reuse: no repositories row (empty or"
                " pre-step-1 legacy DB)"
            )
            seed = "rebuild-artifact"
            if relation == "artifact-ahead":
                notices.append(
                    f"the legacy artifact classifies ahead of {legacy_db}; seeding"
                    " from the artifact so no verdicts are lost"
                )
        elif relation in ("equal", "db-ahead"):
            seed = "reuse-db"
        elif relation == "artifact-ahead":
            notices.append(
                f"the legacy artifact classifies ahead of {legacy_db}; seeding from the"
                " artifact so no verdicts are lost"
            )
            seed = "rebuild-artifact"
        else:
            raise MigrationError(
                f"{legacy_db} and the legacy artifact covered divergent commits;"
                " which one is authoritative cannot be decided here; migrate"
                " with --fresh"
            )
    else:
        seed = "rebuild-artifact"

    _guard_dest(db_path, _expected_dest_key(relabel, stored_shim, stored, resolved), fresh=False)
    return Plan(seed, db_path, legacy_db, relabel, tuple(notices), tuple(cleanup), branch)


def _dest_choice(db_arg: str | None, legacy_arg: str | None) -> Path:
    """Destination DB: explicit --db, else the mirrored home path when the
    legacy DB sits at the documented default location, else the verb
    standard."""
    if db_arg:
        return Path(db_arg)
    legacy = _legacy_db_path(legacy_arg)
    if legacy is not None and legacy == DEFAULT_LEGACY_DB.expanduser():
        return DEFAULT_MIRRORED_DB.expanduser()  # documented layout: mirror dir+file name
    return _default_dest()


def _expected_dest_key(
    relabel: tuple[str, str, str, str] | None, stored_shim: bool, stored: str, resolved: str
) -> str | None:
    """The repositories key the destination DB should carry after migration
    (the previous-attempt signal for _guard_dest)."""
    if relabel is not None:
        return relabel[3]
    if stored_shim:
        return resolved  # upgrade branch: register relabels during the update
    if stored != resolved:
        return stored  # keep branch: stored key stays
    return resolved


def _guard_dest(db_path: Path, expected_key: str | None, fresh: bool) -> None:
    """Refuse to replace a destination DB that already holds data, unless it
    is empty or holds a previous attempt at exactly this repository."""
    if not db_path.exists():
        return
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        tables = {
            r[0]
            for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall()
        }
        if not tables:
            return  # empty file: nothing to protect
        if not {"commits", "repositories"} <= tables:
            raise MigrationError(
                f"destination {db_path} exists with unknown content ({', '.join(sorted(tables))})"
                " — pick another --db"
            )
        commits = int(conn.execute("SELECT COUNT(*) FROM commits").fetchone()[0])
        if commits == 0:
            return
        row = conn.execute("SELECT repo_key FROM repositories").fetchone()
    finally:
        conn.close()
    if fresh:
        raise MigrationError(
            f"destination {db_path} already holds {commits} walked commits; --fresh would"
            " discard them — pick another --db or delete it first"
        )
    dest_key = str(row["repo_key"]) if row is not None else None
    if dest_key != expected_key:
        raise MigrationError(
            f"destination {db_path} already holds {commits} walked commits keyed"
            f" {dest_key!r} — refusing to overwrite it; pick another --db"
        )


def _horizon_relation(repo: Path, legacy_db: Path, artifact_horizon: str) -> str:
    """Compare the legacy DB's walk coverage with the artifact's Coverage
    horizon: 'equal' | 'db-ahead' | 'artifact-ahead' | 'diverged'. Both are
    target-branch commit shas; a git ancestry check decides which side holds
    the newer analysis."""
    conn = _open_read_snapshot(legacy_db)
    try:
        db_horizon = artifact.covered_through(conn)
    finally:
        conn.close()
    if db_horizon == artifact_horizon:
        return "equal"
    if not db_horizon or not artifact_horizon:
        return "artifact-ahead" if not db_horizon else "db-ahead"
    if _ancestor(repo, db_horizon, artifact_horizon):
        return "artifact-ahead"
    if _ancestor(repo, artifact_horizon, db_horizon):
        return "db-ahead"
    return "diverged"


def _ancestor(repo: Path, old: str, new: str) -> bool:
    proc = subprocess.run(
        ["git", "-C", str(repo), "merge-base", "--is-ancestor", old, new],
        capture_output=True,
        check=False,
    )
    return proc.returncode == 0


def _resolved_key(repo: Path, branch: str) -> tuple[str, str, str]:
    """(key base, slug, repository key) of the repo as the identity rules
    resolve it right now (post-rename URLs canonicalize; ssh aliases and
    missing origins fall back to the local: shim)."""
    base, slug, _clone_url = identity.resolved_identity(repo)
    return base, slug, identity.repo_key(base, branch)


def _legacy_db_path(legacy_arg: str | None) -> Path | None:
    """The legacy machine DB when one exists. An explicit, nonexistent path
    is a contradiction (the user asked for it); the implicit default is only
    consulted when present."""
    if legacy_arg is not None:
        p = Path(legacy_arg).expanduser()
        if not p.exists():
            raise MigrationError(f"legacy DB {p} does not exist; pass the real path")
        return p
    return DEFAULT_LEGACY_DB.expanduser() if DEFAULT_LEGACY_DB.expanduser().exists() else None


def _default_dest() -> Path:
    """The verb-standard DB default, relative to the caller's cwd."""
    return Path("coding-stats.db")


def _open_read_snapshot(path: Path) -> sqlite3.Connection:
    """A consistent in-memory read snapshot of a (legacy) SQLite DB.

    A plain ``mode=ro`` open is NOT enough here: legacy DBs run in WAL
    mode (persistent in the file header), and a read-only connection
    cannot create the ``-shm``/``-wal`` sidecars when they are absent —
    the open (or the first read) fails with an OperationalError that
    looks like a missing table. A normal connection may create sidecars
    (harmless: this file is machine-local state the migration owns), and
    the backup API yields one consistent snapshot including WAL content."""
    src = sqlite3.connect(path)
    try:
        snap = sqlite3.connect(":memory:")
        try:
            src.backup(snap)
        except Exception:
            snap.close()
            raise
    finally:
        src.close()
    snap.row_factory = sqlite3.Row
    return snap


def _stored_db_key(path: Path) -> str | None:
    conn = _open_read_snapshot(path)
    try:
        rows = conn.execute("SELECT repo_key FROM repositories").fetchall()
    except sqlite3.OperationalError:
        # a pre-step-1 legacy DB (the old tool's own schema) has no
        # repositories table: no usable key — rebuild-from-artifact territory
        return None
    finally:
        conn.close()
    if not rows:
        return None
    if len(rows) > 1:
        raise MigrationError(f"legacy DB {path} holds multiple repositories rows")
    return str(rows[0]["repo_key"])


def describe(plan: Plan) -> list[str]:
    """The plan as printed lines — used by --dry-run and by the real run."""
    out = [f"note: {n}" for n in plan.notices]
    out.append(f"seed: {plan.seed} -> {plan.db_path}")
    if plan.legacy_db is not None:
        out.append(f"legacy DB: {plan.legacy_db}")
    if plan.relabel:
        out.append(f"relabel repository key {plan.relabel[0]!r} -> {plan.relabel[3]!r} (rename)")
    out.append(f"cleanup: {', '.join(plan.cleanup) if plan.cleanup else '(nothing)'}")
    return out


def run(plan: Plan, repo: Path, no_classify: bool = False) -> list[str]:
    """Execute the plan. Returns the printed lines."""
    out = describe(plan)
    if plan.seed == "already":
        out.append("already migrated: .coding-stats artifact verifies")
        _cleanup(plan, repo)
        return out

    plan.db_path.parent.mkdir(parents=True, exist_ok=True)
    if plan.seed == "reuse-db":
        assert plan.legacy_db is not None
        _atomic_copy(plan.legacy_db, plan.db_path)
    elif plan.seed == "rebuild-artifact":
        # seed from the legacy artifact bytes whether or not a legacy DB was
        # also found (the behind case: the artifact carries newer verdicts)
        _rebuild_from_artifact(plan.db_path, (repo / OLD_ARTIFACT_REL).read_bytes(), repo)

    conn = db.connect(plan.db_path)
    try:
        if plan.relabel:
            _relabel(conn, plan.relabel, plan.branch)
        for key, value in (("repo", str(repo)), ("branch", plan.branch)):
            # settings values are JSON-encoded (cli._set convention)
            conn.execute(
                "INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)",
                (key, json.dumps(value)),
            )
        conn.commit()
    finally:
        conn.close()

    from .cli import _run_update  # late import: cli imports this module at top level

    conn = db.connect(plan.db_path)
    try:
        conn = _run_update(
            conn,
            plan.db_path,
            argparse.Namespace(
                no_classify=no_classify,
                no_detect=False,
                no_lineage=False,
                no_report=False,
                no_serialize=False,
            ),
            legacy_store=True,
        )
    finally:
        conn.close()

    new_art = repo / NEW_ARTIFACT_REL
    err = artifact.verify(new_art)
    if err is not None:
        raise MigrationError(f"the regenerated artifact does not verify ({err}); legacy files kept")
    _cleanup(plan, repo)
    out.append(f"migrated: {new_art} verifies; legacy files removed")
    return out


def _rebuild_from_artifact(db_path: Path, data: bytes, repo: Path) -> None:
    """Fresh working DB seeded from verified legacy artifact bytes: the
    verdict rows travel inside the artifact, so classification cost is zero.
    register_repository is deliberately NOT used — migration relabels the
    repositories row itself (the rename is an identity change the register
    rules must refuse; see module docstring)."""
    tmp_path = db_path.parent / (db_path.name + ".migrate-tmp")
    for suffix in ("", *_SIDECARS):
        Path(str(tmp_path) + suffix).unlink(missing_ok=True)
    raw = sqlite3.connect(tmp_path)
    raw.row_factory = sqlite3.Row
    try:
        artifact.materialize(raw, data)
        artifact.stamp_schema_steps(raw, data)
    finally:
        raw.close()
    conn = db.connect(tmp_path)
    try:
        recovery.rehydrate_diffs(conn, repo)
        conn.commit()
    finally:
        conn.close()
    _atomic_swap(tmp_path, db_path)


def _atomic_copy(source: Path, db_path: Path) -> None:
    """Consistent copy of the legacy DB through a tmp file + atomic swap
    (the sqlite backup API handles WAL consistency; the destination is never
    in a half-open state)."""
    tmp_path = db_path.parent / (db_path.name + ".migrate-tmp")
    for suffix in ("", *_SIDECARS):
        Path(str(tmp_path) + suffix).unlink(missing_ok=True)
    src = _open_read_snapshot(source)
    try:
        dst = sqlite3.connect(tmp_path)
        try:
            src.backup(dst)
        finally:
            dst.close()
    finally:
        src.close()
    _atomic_swap(tmp_path, db_path)


def _atomic_swap(tmp_path: Path, db_path: Path) -> None:
    """Replace db_path with tmp_path atomically; stale destination sidecars
    are removed only after the main file is in place (they would otherwise
    replay old frames onto the new file)."""
    tmp_path.replace(db_path)
    for suffix in _SIDECARS:
        Path(str(db_path) + suffix).unlink(missing_ok=True)
        Path(str(tmp_path) + suffix).unlink(missing_ok=True)


def _relabel(conn: sqlite3.Connection, relabel: tuple[str, str, str, str], branch: str) -> None:
    """The one write register_repository refuses: relabel the repositories
    row to the resolved (post-rename) identity, explicitly and loudly."""
    old_key, base, slug, new_key = relabel
    conn.execute(
        "UPDATE repositories SET repo_key = ?, slug = ?, branch = ?, clone_url = ?"
        " WHERE repo_key = ?",
        (new_key, slug, branch, base, old_key),
    )


def _cleanup(plan: Plan, repo: Path) -> None:
    for rel in plan.cleanup:
        path = repo / rel.rstrip("/")
        if rel.endswith("/"):
            shutil.rmtree(path, ignore_errors=True)
        else:
            path.unlink(missing_ok=True)


def init_ci(repo: Path, branch: str, upgrade: bool = False) -> list[str]:
    """Write the coding-stats CI scaffold (the legacy workflow was already
    deleted by the cleanup pass)."""
    from . import ci  # late import keeps module-level deps flat

    return ci.init(repo, branch, upgrade=upgrade)


def migrate_to_data_branch(
    repo: Path, target: str | None = None, remote: str = "origin"
) -> list[str]:
    """ADR-0006 clause 6 (ticket #26): move a repo from the ADR-0003 layout
    (a committed .coding-stats/ store on the Target branch) onto its orphan
    Data branch. Verifies first (refusing damage), re-prefixes the ids, and
    pushes ONLY refs/heads/coding-stats/<target>; the Target branch itself
    never receives a commit. Idempotent: a Data branch already holding a
    verifying, branch-carrying artifact reports 'already migrated'."""
    from . import ci, datastore, gitwalk, identity  # late imports (module cycle)

    branch = target or gitwalk.current_branch(repo)
    legacy = repo / ".coding-stats" / "coding-stats.sql"
    out: list[str] = []
    # idempotent only against a VERIFYING artifact: a Data branch whose tip
    # carries no (or a damaged) artifact does not count as migrated — the
    # migration below overwrites it with the Target's verified store
    data_tip = datastore.remote_data_refs(repo, remote).get(datastore.data_branch(branch))
    if data_tip is not None:
        data = datastore.read_artifact_at(repo, data_tip)
        if data is not None and artifact.verify_bytes(data) is None:
            return ["already migrated"]

    if not legacy.exists():
        return ["nothing to migrate (no committed .coding-stats/ on this Target)"]
    err = artifact.verify(legacy)
    if err is not None:
        raise MigrationError(
            f"the committed .coding-stats/ artifact does not verify ({err}); nothing migrated"
        )
    out.append("committed artifact: digest ok")
    # re-prefix in memory: the ids upgrade to the {repo}@{branch} form
    rows = sqlite3.connect(":memory:")
    rows.row_factory = sqlite3.Row
    try:
        artifact.materialize(rows, legacy.read_bytes())
        plain = identity.resolved_identity(repo)[1]
        identity.reprefix_features(rows, identity.repo_slug(plain, branch))
        data = artifact.serialize(rows)
    finally:
        rows.close()
    out.append("ids re-prefixed to {repo}@{branch}")

    store = datastore.prepare(repo, branch)
    art = store.worktree / ".coding-stats" / "coding-stats.sql"
    art.parent.mkdir(parents=True, exist_ok=True)
    art.write_bytes(data)
    landing = ci.land(store, repo, remote)
    out.append(f"coding-stats landing: {landing.status} — {landing.detail}")
    if landing.status != "landed":
        out.append(
            "NOT removed from the Target branch: the landing did not push"
            " (keep .coding-stats/ until a run lands the Data branch, then"
            " re-run migrate)"
        )
        return out
    # the old-rendered scaffold goes WITH the store; an actions-based caller
    # workflow (already the adopter shape) stays untouched
    old = repo / ci.WORKFLOW_REL
    is_old_scaffold = old.exists() and "uv tool install" in old.read_text(encoding="utf-8")
    scaffold_line = (
        "  rm .github/workflows/coding-stats.yml  # the old rendered scaffold;"
        " regenerate with 'coding-stats ci init'\n"
        if is_old_scaffold
        else ""
    )
    out.append(
        "removal is a normal PR (migration never pushes to the Target branch): next steps\n"
        "  git checkout <target>\n"
        "  git rm -r .coding-stats\n"
        f"{scaffold_line}"
        "  git commit -m 'drop the in-branch stats store (moved to the Data branch)'\n"
        "  git push origin <target>"
    )
    return out
