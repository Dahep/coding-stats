"""Legacy skill-stats migration (ADR-0005): one verb that moves a Target repo
from the pre-rename layout to coding-stats.

Migrated surfaces per repo:

* the committed artifact (``.skill-stats/skill-stats.sql`` -> a fresh
  ``.coding-stats/`` store, regenerated by the normal update flow),
* the machine-local working DB (``~/.skill-stats/skill-stats.db`` reused
  when it corresponds to the legacy artifact — its verdicts and classify
  session survive; otherwise a fresh DB is rebuilt from the legacy artifact
  bytes, whose verdict rows travel inside the artifact),
* the Repository key when the GitHub rename changed it: the tool's identity
  rules (identity.register_repository) refuse key changes on DBs holding
  data — correctly, they cannot tell a rename from pointing a DB at a
  different repo. Migration is the explicit, user-invoked authority for
  exactly that one case: the legacy artifact digest is verified first, so
  the DB provably belongs to this repository, and only then is the key
  relabelled to the resolved identity.
* the CI scaffold: the legacy ``skill-stats.yml`` is deleted (it would keep
  running the old tool forever) and ``ci init`` optionally writes the new
  workflow.

The legacy ``.skill-stats/`` directory is removed only after the new store
verifies on disk — a failed update never destroys the old artifact. The
second run of this verb is a no-op cleanup (idempotent).
"""

import argparse
import json
import shutil
import sqlite3
from dataclasses import dataclass
from pathlib import Path

from . import artifact, db, identity, recovery

OLD_STORE_DIR = ".skill-stats"
OLD_ARTIFACT_REL = ".skill-stats/skill-stats.sql"
OLD_WORKFLOW_REL = ".github/workflows/skill-stats.yml"
NEW_ARTIFACT_REL = ".coding-stats/coding-stats.sql"

DEFAULT_LEGACY_DB = Path("~/.skill-stats/skill-stats.db")
DEFAULT_MIRRORED_DB = Path("~/.coding-stats/coding-stats.db")

_SIDECARS = ("-wal", "-shm", "-journal")


class MigrationError(RuntimeError):
    """Migration cannot proceed safely; nothing was changed."""


@dataclass(frozen=True)
class Plan:
    """What migrate will do and why. Printed verbatim by --dry-run."""

    seed: str  # 'already' | 'reuse-db' | 'rebuild-artifact' | 'fresh'
    db_path: Path
    legacy_db: Path | None
    relabel: tuple[str, str, str, str] | None  # stored key, base, slug, new key
    notices: tuple[str, ...]
    cleanup: tuple[str, ...]
    branch: str


def detect(
    repo: Path,
    db_arg: str | None,
    legacy_arg: str | None,
    fresh: bool,
    branch: str,
) -> Plan:
    """Inspect the repo's legacy state and decide the seed, the destination
    DB, the rename relabel, and the cleanup list. Explicit user input
    (--legacy-db) that contradicts reality is an error; implicit defaults
    (a legacy DB found at the default path) never are — they downgrade to a
    safer seed with a notice."""
    cleanup: list[str] = []
    if (repo / OLD_WORKFLOW_REL).exists():
        cleanup.append(OLD_WORKFLOW_REL)
    if (repo / OLD_STORE_DIR).exists():
        cleanup.append(OLD_STORE_DIR + "/")
    notices: list[str] = []
    db_path = Path(db_arg) if db_arg else _default_dest()
    legacy_db = _legacy_db_path(legacy_arg)
    if (repo / NEW_ARTIFACT_REL).exists() and artifact.verify(repo / NEW_ARTIFACT_REL) is None:
        return Plan("already", db_path, None, None, tuple(notices), tuple(cleanup), branch)
    if fresh:
        return Plan("fresh", db_path, None, None, tuple(notices), tuple(cleanup), branch)

    old_art = repo / OLD_ARTIFACT_REL
    err = artifact.verify(old_art) if old_art.exists() else "missing"
    if err is not None:
        if err != "missing":
            notices.append(f"legacy artifact fails verification ({err}); migrating fresh")
        return Plan("fresh", db_path, None, None, tuple(notices), tuple(cleanup), branch)

    header = artifact.parse_header(old_art.read_bytes())
    if header is None:
        notices.append("legacy artifact has no parsable header; migrating fresh")
        return Plan("fresh", db_path, None, None, tuple(notices), tuple(cleanup), branch)

    stored = header.repository_key
    explicit = legacy_arg is not None
    if legacy_db is not None:
        db_key = _stored_db_key(legacy_db)
        if db_key is None:
            raise MigrationError(f"legacy DB {legacy_db} has no repositories row")
        if db_key != stored:
            if explicit:
                raise MigrationError(
                    f"legacy DB {legacy_db} is keyed {db_key!r} but the legacy artifact is"
                    f" keyed {stored!r} — they do not correspond; migrate without"
                    " --legacy-db or with --fresh"
                )
            notices.append(
                f"ignoring {legacy_db}: keyed {db_key!r}, not this repository's legacy artifact"
            )
            legacy_db = None
    else:
        notices.append(
            "no legacy machine DB found; seeding the new DB from the legacy artifact"
            " (verdicts travel inside it)"
        )

    base, slug, clone_url, resolved = _resolved_key(repo, branch)
    relabel: tuple[str, str, str, str] | None = None
    stored_shim = stored.startswith("local:")
    resolved_shim = base.startswith("local:")
    if stored == resolved:
        pass
    elif not stored_shim and not resolved_shim:
        relabel = (stored, base, slug, resolved)  # the GitHub rename, by explicit authority
    elif stored_shim and resolved_shim:
        raise MigrationError(
            f"legacy identity {stored!r} cannot relabel to {resolved!r}"
            " (shim-to-shim move); migrate with --fresh"
        )
    elif stored_shim:
        # shim -> canonical is the documented upgrade flow: register_repository
        # relabels it (with a warning) during the post-migration update
        notices.append(
            f"shim identity {stored!r} upgrades to the canonical {resolved!r}"
            " during the migration update"
        )
    else:
        notices.append(
            f"origin URL unavailable on this machine (resolved {resolved!r}); the stored"
            f" key {stored!r} is kept — register_repository warns and continues"
        )

    if db_path == _default_dest() and legacy_db == DEFAULT_LEGACY_DB.expanduser():
        db_path = DEFAULT_MIRRORED_DB  # documented layout: mirror dir+file name
    seed = "reuse-db" if legacy_db is not None else "rebuild-artifact"
    return Plan(seed, db_path, legacy_db, relabel, tuple(notices), tuple(cleanup), branch)


def _resolved_key(repo: Path, branch: str) -> tuple[str, str, str | None, str]:
    """(key base, slug, clone URL, full repository key) of the repo as the
    identity rules resolve it right now (post-rename URLs canonicalize; ssh
    aliases and missing origins fall back to the local: shim)."""
    base, slug, clone_url = identity.resolved_identity(repo)
    return base, slug, clone_url, identity.repo_key(base, branch)


def _legacy_db_path(legacy_arg: str | None) -> Path | None:
    """The legacy machine DB when one exists (explicit path, else the
    documented default location)."""
    if legacy_arg is not None:
        p = Path(legacy_arg).expanduser()
        return p if p.exists() else None
    return DEFAULT_LEGACY_DB.expanduser() if DEFAULT_LEGACY_DB.expanduser().exists() else None


def _default_dest() -> Path:
    """The verb-standard DB default, relative to the caller's cwd."""
    return Path("coding-stats.db")


def _stored_db_key(path: Path) -> str | None:
    conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        rows = conn.execute("SELECT repo_key FROM repositories").fetchall()
    finally:
        conn.close()
    if not rows:
        return None
    if len(rows) > 1:
        raise MigrationError(f"legacy DB {path} holds multiple repositories rows")
    return str(rows[0]["repo_key"])


def describe(plan: Plan) -> list[str]:
    """The plan as printed lines — used by --dry-run and by the real run."""
    out = [f"note: {n}" for n in plan.notices]
    out.append(f"seed: {plan.seed} -> {plan.db_path}")
    if plan.legacy_db is not None:
        out.append(f"legacy DB: {plan.legacy_db}")
    if plan.relabel:
        out.append(f"relabel repository key {plan.relabel[0]!r} -> {plan.relabel[3]!r} (rename)")
    out.append(f"cleanup: {', '.join(plan.cleanup) if plan.cleanup else '(nothing)'}")
    return out


def run(plan: Plan, repo: Path, no_classify: bool = False) -> list[str]:
    """Execute the plan. Returns the printed lines. The old store is removed
    only after the regenerated new artifact verifies."""
    out = describe(plan)
    if plan.seed == "already":
        out.append("already migrated: .coding-stats artifact verifies")
        _cleanup(plan, repo)
        return out

    if plan.seed == "reuse-db":
        assert plan.legacy_db is not None
        plan.db_path.parent.mkdir(parents=True, exist_ok=True)
        _backup_db(plan.legacy_db, plan.db_path)
    elif plan.seed == "rebuild-artifact":
        assert plan.legacy_db is None
        data = (repo / OLD_ARTIFACT_REL).read_bytes()
        _rebuild_from_artifact(plan.db_path, data, repo)
    else:
        plan.db_path.parent.mkdir(parents=True, exist_ok=True)

    conn = db.connect(plan.db_path)
    try:
        if plan.relabel:
            _relabel(conn, plan.relabel, plan.branch)
        for key, value in (("repo", str(repo)), ("branch", plan.branch)):
            # settings values are JSON-encoded (cli._set convention)
            conn.execute(
                "INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)",
                (key, json.dumps(value)),
            )
        conn.commit()
    finally:
        conn.close()

    from .cli import _run_update  # late import: cli imports this module at top level

    conn = db.connect(plan.db_path)
    try:
        conn = _run_update(
            conn,
            plan.db_path,
            argparse.Namespace(
                no_classify=no_classify,
                no_detect=False,
                no_lineage=False,
                no_report=False,
                no_serialize=False,
            ),
        )
    finally:
        conn.close()

    new_art = repo / NEW_ARTIFACT_REL
    err = artifact.verify(new_art)
    if err is not None:
        raise MigrationError(f"the regenerated artifact does not verify ({err}); legacy files kept")
    _cleanup(plan, repo)
    out.append(f"migrated: {new_art} verifies; legacy files removed")
    return out


def _rebuild_from_artifact(db_path: Path, data: bytes, repo: Path) -> None:
    """Fresh working DB seeded from verified legacy artifact bytes: the
    verdict rows travel inside the artifact, so classification cost is zero.
    register_repository is deliberately NOT used — migration relabels the
    repositories row itself (the rename is an identity change the register
    rules must refuse; see module docstring)."""
    tmp_path = db_path.parent / (db_path.name + ".migrate-tmp")
    for suffix in ("", *_SIDECARS):
        Path(str(tmp_path) + suffix).unlink(missing_ok=True)
    raw = sqlite3.connect(tmp_path)
    raw.row_factory = sqlite3.Row
    try:
        artifact.materialize(raw, data)
        artifact.stamp_schema_steps(raw, data)
    finally:
        raw.close()
    conn = db.connect(tmp_path)
    try:
        recovery.rehydrate_diffs(conn, repo)
        conn.commit()
    finally:
        conn.close()
    for suffix in ("", *_SIDECARS):  # stale sidecars of a previous dest would replay old frames
        Path(str(db_path) + suffix).unlink(missing_ok=True)
    try:
        tmp_path.replace(db_path)
    finally:
        for suffix in _SIDECARS:
            Path(str(tmp_path) + suffix).unlink(missing_ok=True)


def _backup_db(source: Path, dest: Path) -> None:
    """Consistent copy of the legacy DB (sqlite backup API: WAL-safe)."""
    src = sqlite3.connect(f"file:{source}?mode=ro", uri=True)
    try:
        dst = sqlite3.connect(dest)
        try:
            src.backup(dst)
        finally:
            dst.close()
    finally:
        src.close()


def _relabel(conn: sqlite3.Connection, relabel: tuple[str, str, str, str], branch: str) -> None:
    """The one write register_repository refuses: relabel the repositories
    row to the resolved (post-rename) identity, explicitly and loudly."""
    old_key, base, slug, new_key = relabel
    conn.execute(
        "UPDATE repositories SET repo_key = ?, slug = ?, branch = ?, clone_url = ?"
        " WHERE repo_key = ?",
        (new_key, slug, branch, base, old_key),
    )


def _cleanup(plan: Plan, repo: Path) -> None:
    for rel in plan.cleanup:
        path = repo / rel.rstrip("/")
        if rel.endswith("/"):
            shutil.rmtree(path, ignore_errors=True)
        else:
            path.unlink(missing_ok=True)


def init_ci(repo: Path, branch: str, upgrade: bool = False) -> list[str]:
    """Write the coding-stats CI scaffold (the legacy workflow was already
    deleted by the cleanup pass)."""
    from . import ci  # late import keeps module-level deps flat

    return ci.init(repo, branch, upgrade=upgrade)
